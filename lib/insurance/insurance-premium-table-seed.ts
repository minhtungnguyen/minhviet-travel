function buildZoneRates(zone: InsuranceZone): PremiumRate[] {
  const rows = ZONE_ROWS[zone]
  return INSURANCE_DURATION_BANDS.flatMap((band, index) => {
    const [aUsd, bUsd, cUsd, aVnd, bVnd, cVnd] = rows[index]
    return [
      { zone, plan: 'A' as const, minDays: band.minDays, maxDays: band.maxDays, rate: { usd: aUsd, vnd: aVnd } },
      { zone, plan: 'B' as const, minDays: band.minDays, maxDays: band.maxDays, rate: { usd: bUsd, vnd: bVnd } },
      { zone, plan: 'C' as const, minDays: band.minDays, maxDays: band.maxDays, rate: { usd: cUsd, vnd: cVnd } },
    ]
  })
}

